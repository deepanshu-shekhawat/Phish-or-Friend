"""Regenerates every pixel-art asset, fonts, tokens and data files.

    python3 tools/build_assets.py

All art is original and drawn in code (tools/art_*.py) so it is reproducible and
has no third-party licensing burden.  Only the three fonts are third-party (OFL).
"""
import json, os, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pixel
from pixel import P, MANIFEST, ROOT, write_text
import art_boot, art_icons, art_ui, art_people, art_props

PROJECT = os.path.abspath(os.path.join(ROOT, '..', '..', '..'))


def tokens_css():
    names = {'face': 'face', 'hi': 'hilight', 'mid': 'light', 'shade': 'shadow', 'dark': 'dkshadow', 'black': 'black', 'navy': 'title', 'blue': 'accent',
             'sky': 'sky', 'teal': 'desktop', 'green': 'term', 'dgreen': 'ok', 'red': 'bad', 'orange': 'warn', 'yellow': 'hint', 'tip': 'tooltip', 'paper': 'paper', 'ink': 'ink'}
    lines = ['/* GENERATED by tools/build_assets.py from tools/pixel.py palette - do not edit */', ':root {']
    for k, v in names.items(): lines.append(f'  --cd-{v}: {P[k]};')
    lines += ['  --cd-title2: #1084d0;', '  --cd-inactive: #808080;', '  --cd-inactive2: #b0b0b0;', '}']
    return '\n'.join(lines) + '\n'


def fonts():
    nm = os.path.join(PROJECT, 'node_modules', '@fontsource')
    spec = [('vt323', 'vt323-latin-400-normal', 'CyberDesk Mono', 'Monospace terminal font (VT323)', [90]),
            ('press-start-2p', 'press-start-2p-latin-400-normal', 'CyberDesk Bitmap', 'Bitmap display font (Press Start 2P)', [91]),
            ('pixelify-sans', 'pixelify-sans-latin-400-normal', 'CyberDesk UI', 'Primary UI font (Pixelify Sans)', [89])]
    css = ['/* GENERATED. Fonts are SIL OFL 1.1; see assets/cyberdesk/LICENSES/ */']
    licences = ['# Third-party assets\n', 'The only third-party assets in the CyberDesk library are the three fonts below, all SIL Open Font License 1.1, '
                'obtained from the @fontsource npm packages (v5.3.0). Everything else (pixel art, audio, UI) is original work generated by the scripts in `tools/`.\n',
                '| Font | Use | Source | Licence |\n|---|---|---|---|']
    for pkg, fn, fam, note, rows in spec:
        for ext in ('woff2', 'woff'):
            src = os.path.join(nm, pkg, 'files', f'{fn}.{ext}')
            dst = os.path.join(ROOT, 'fonts', f'{fn}.{ext}')
            os.makedirs(os.path.dirname(dst), exist_ok=True); shutil.copy(src, dst)
            MANIFEST.append(dict(file=f'assets/cyberdesk/fonts/{fn}.{ext}', rows=rows, grid='', component='fonts.css', note=note))
        css.append(f"@font-face {{ font-family: '{fam}'; src: url('./{fn}.woff2') format('woff2'), url('./{fn}.woff') format('woff'); font-weight: 400; font-style: normal; font-display: swap; }}")
        lic = os.path.join(ROOT, 'LICENSES', f'{pkg}-OFL.txt')
        os.makedirs(os.path.dirname(lic), exist_ok=True)
        shutil.copy(os.path.join(nm, pkg, 'LICENSE'), lic)
        licences.append(f'| {note} | CSS family `{fam}` | https://fontsource.org/fonts/{pkg} | SIL OFL 1.1 - `LICENSES/{pkg}-OFL.txt` |')
    write_text('fonts/fonts.css', '\n'.join(css) + '\n', [89, 90, 91], 'fonts.css', 'font-face declarations')
    licences += ['\n## Original work\n',
                 'All pixel-art, sprites, wallpapers, cursors, sound effects and UI components were created for this project. No proprietary logos, '
                 'artwork or sounds are copied. "CyberDesk" and the emblem are fictional. The visual style is a generic homage to 1990s desktop UIs.\n',
                 'Owner decision needed: choose a licence for the original assets (not chosen automatically).\n']
    write_text('LICENSES/THIRD_PARTY.md', '\n'.join(licences), [89, 90, 91], 'docs', 'attribution record')



def data_assets(people):
    write_text('data/signatures.json', json.dumps(SIGNATURES, indent=2), [43], 'Mail/EmailBody', '8 fictional signatures')
    write_text('data/layouts.json', json.dumps(LAYOUTS, indent=2), [44], 'Mail/EmailBody', '6 body layouts (block lists rendered by EmailBody)')
    write_text('data/contacts.json', json.dumps(people['contacts'], indent=2), [42], 'Mail', '20 avatars')
    write_text('data/progression.json', json.dumps(dict(ranks=people['ranks'], achievements=people['achievements'], mascot=people['mascot']), indent=2), [80, 81, 88], 'Progression')


def main():
    art_boot.build()
    app = art_icons.build()
    ui = art_ui.build()
    people = art_people.build()
    art_props.build()
    fonts()
    data_assets(people)
    os.makedirs(os.path.join(PROJECT, 'src', 'cyberdesk', 'styles'), exist_ok=True)
    with open(os.path.join(PROJECT, 'src', 'cyberdesk', 'styles', 'tokens.css'), 'w') as f: f.write(tokens_css())
    cursors = dict(ui['cursors'])
    idx = dict(icons=app, toolbar=ui['toolbar'], nav=ui['nav'], attach=ui['attach'], threats=ui['threats'], evidence=ui['evidence'],
               cursors={n: list(h) for n, h in ui['cursors']}, ranks=[r['id'] for r in people['ranks']], achievements=[a['id'] for a in people['achievements']],
               contacts=[c['id'] for c in people['contacts']], mascot=people['mascot'])
    with open(os.path.join(PROJECT, 'src', 'cyberdesk', 'assetIndex.json'), 'w') as f: json.dump(idx, f, indent=1)
    with open(os.path.join(ROOT, 'manifest.files.json'), 'w') as f: json.dump(MANIFEST, f, indent=1)
    print('files registered:', len(MANIFEST))


if __name__ == '__main__':
    main()
